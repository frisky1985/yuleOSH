class TestExtractPrdRequirements:
    def test_table_style_with_section(self):
        prd = (
            "### 4.1 硬件抽象层 (SR-001)\n\n"
            "| 需求 ID | 描述 | 优先级 | 实现说明 |\n"
            "|---------|------|--------|---------|\n"
            "| FR-001 | 提供电机和霍尔传感器的 HAL 抽象层 | P0 | 定义接口 |\n"
            "| FR-002 | 支持 PWM 输出控制电机速度 | P0 | 线性映射 |\n"
        )
        reqs = _extract_prd_requirements(prd)
        assert len(reqs) == 2
        assert reqs[0]["id"] == "FR-001"
        assert "HAL 抽象层" in reqs[0]["text"]
        assert reqs[0]["section"] == "SR-001"
        assert reqs[1]["section"] == "SR-001"

    def test_header_row_skipped(self):
        prd = (
            "| 需求 ID | 描述 | 优先级 | 实现说明 |\n"
            "|---------|------|--------|---------|\n"
            "| FR-001 | 实际需求 | P0 | note |\n"
        )
        reqs = _extract_prd_requirements(prd)
        assert len(reqs) == 1
        assert reqs[0]["id"] == "FR-001"

    def test_heading_style_requirements(self):
        prd = (
            "### FR-001 手动模式\n"
            "The system SHALL run motor while held\n"
        )
        reqs = _extract_prd_requirements(prd)
        # heading itself contributes one requirement; the SHALL line another
        assert any(r["id"] == "FR-001" for r in reqs)
        assert any("run motor" in r["text"] for r in reqs)

    def test_freeform_keyword_lines(self):
        prd = (
            "### 需求\n"
            "系统必须支持防夹检测\n"
        )
        reqs = _extract_prd_requirements(prd)
        # heading itself is skipped; the free-form line carries 必须/支持
        assert any("防夹" in r["text"] for r in reqs)

    def test_skips_code_blocks_and_quotes(self):
        prd = (
            "> Generated by LLM\n"
            "```\n"
            "| FR-999 | fake table inside code |\n"
            "```\n"
            "| FR-001 | real requirement | P0 | note |\n"
        )
        reqs = _extract_prd_requirements(prd)
        assert len(reqs) == 1
        assert reqs[0]["id"] == "FR-001"

    def test_empty_prd(self):
        assert _extract_prd_requirements("") == []


