"""
Unit tests for yuleosh.pipeline.step_handlers.review_prd — PRD quality review.

Covers the G-50 fix for the PRD review false-negative:
  - Old extractor only recognised `Req-NNN` headings → 0 requirements
    extracted from table-style PRDs (| FR-001 | 描述 | ... |).
  - Old matcher only did ASCII keyword overlap → Chinese PRD text never
    matched English SHALL statements (cross-language false negative).
  - No section-ID alignment: spec `### SR-001` ↔ PRD `### 4.1 (SR-001)`.

Target functions:
  - _extract_shalls
  - _extract_prd_requirements
  - _check_shall_coverage
  - _cjk_tokens
"""


from yuleosh.pipeline.step_handlers.review_prd import (
    _check_shall_coverage,
    _cjk_tokens,
    _extract_prd_requirements,
    _extract_shalls,
)

# ===================================================================
# _extract_shalls
# ===================================================================

class TestExtractShalls:
    def test_basic_list_shall(self):
        spec = (
            "### SR-001: 硬件抽象\n"
            "- The system SHALL provide a HAL abstraction layer\n"
            "- The system SHALL support PWM output\n"
        )
        shalls = _extract_shalls(spec)
        assert len(shalls) == 2
        assert all(s["section"] == "SR-001" for s in shalls)
        assert shalls[0]["kind"] == "SHALL"
        assert "HAL abstraction" in shalls[0]["statement"]

    def test_tracks_multiple_sections(self):
        spec = (
            "### SR-001: A\n"
            "- The system SHALL do A\n"
            "### SW-004: B\n"
            "- The system SHALL do B\n"
        )
        shalls = _extract_shalls(spec)
        assert [s["section"] for s in shalls] == ["SR-001", "SW-004"]

    def test_shall_not_kind(self):
        spec = "- Application modules SHALL NOT access registers\n"
        shalls = _extract_shalls(spec)
        assert len(shalls) == 1
        assert shalls[0]["kind"] == "SHALL NOT"

    def test_no_shall_returns_empty(self):
        assert _extract_shalls("Just some prose without requirements.") == []

    def test_dedup_same_statement(self):
        spec = (
            "- The system SHALL do the thing\n"
            "- The system SHALL do the thing\n"
        )
        assert len(_extract_shalls(spec)) == 1


