"""Bundled skill packs — third-party skill libraries shipped with yuleOSH.

Packs are generated by ``scripts/import-automotive-skills.py`` and stored as
a single JSON document next to this module.  They are registered into the
process-wide :class:`~yuleosh.skills.registry.SkillRegistry` so every
project can use them without copying files.

Disable with ``YULEOSH_SKILL_PACKS=0`` (tests / minimal installs).
"""

from __future__ import annotations

import json
import logging
import os
from functools import lru_cache
from pathlib import Path

from yuleosh.skills.model import Skill

log = logging.getLogger("yuleosh.skills.packs")

PACKS_DIR = Path(__file__).resolve().with_name("packs")
AUTOMOTIVE_PACK = PACKS_DIR / "automotive" / "skills.json"
PACK_TAG = "automotive"


def packs_enabled() -> bool:
    return os.environ.get("YULEOSH_SKILL_PACKS", "1").strip().lower() not in {
        "0", "false", "off", "no",
    }


@lru_cache(maxsize=4)
def _load_pack(path_str: str) -> tuple[Skill, ...]:
    path = Path(path_str)
    if not path.is_file():
        return ()
    payload = json.loads(path.read_text(encoding="utf-8"))
    skills: list[Skill] = []
    for entry in payload.get("skills", []):
        try:
            skills.append(Skill.from_dict(entry))
        except (TypeError, ValueError) as exc:  # pragma: no cover — corrupt pack
            log.warning("skill pack entry skipped: %s", exc)
    return tuple(skills)


def load_automotive_skills() -> list[Skill]:
    """Return the bundled automotive pack (empty when missing/disabled)."""
    if not packs_enabled():
        return []
    return list(_load_pack(str(AUTOMOTIVE_PACK)))


def install_automotive_pack(registry) -> int:
    """Register the automotive pack into ``registry`` (bulk, no index hook).

    Existing skills with the same name are preserved.  Returns the number of
    newly registered skills.
    """
    skills = load_automotive_skills()
    if not skills:
        return 0
    added = registry.register_many(skills, index=False)
    if added:
        log.info("Registered %d bundled automotive skills", added)
    return added
