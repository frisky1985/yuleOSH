"""Demo 用 mock LLM —— 在没有 LLM_API_KEY 的环境下让 spec 生成链路可跑通。

只服务 demo / 本地验证：把一段自然语言粗分成「主体 / 约束 / 清单项 / 行为」，
渲染成 ``## RS-001:`` + SHALL 的 OpenSpec 草稿。该格式能同时通过
``spec.validate.parse_spec`` 与 ``pipeline.stages.spec._parse_requirements``。

不参与任何生产路径；真实生成仍走 ``generate_spec`` 的默认 LLM。
"""

from __future__ import annotations

import re
from typing import Callable

__all__ = ["build_mock_spec", "make_mock_llm"]

_LEADING_VERBS = (
    "请帮我", "请", "帮我", "我需要", "需要", "要求", "实现", "开发",
    "做一个", "新增", "添加", "支持", "提供",
)
_CLAUSE_SPLIT = re.compile(r"[，。；\n]+")
_LIST_SPLIT = re.compile(r"[、,和及]")
_CONSTRAINT_RE = re.compile(r"\d+\s*(?:ms|毫秒|s|秒|%|MB|KB|GB|次|个)")
_LIST_HEAD_RE = re.compile(r"(包括|包含|涵盖)")


def _analyze(text: str) -> dict:
    """把自然语言输入粗分成结构化片段。"""
    subject = ""
    constraints: list[str] = []
    items: list[str] = []
    behaviors: list[str] = []
    item_label = ""

    for idx, raw in enumerate(c for c in _CLAUSE_SPLIT.split(text) if c.strip()):
        clause = raw.strip()
        for verb in _LEADING_VERBS:
            if clause.startswith(verb):
                clause = clause[len(verb):].strip()
                break
        if not clause:
            continue

        list_head = _LIST_HEAD_RE.search(clause)
        if list_head:
            head = clause[:list_head.start()].strip()
            tail = clause[list_head.end():].strip()
            if head:
                item_label = item_label or head
            for part in _LIST_SPLIT.split(tail):
                part = part.strip().strip("的").strip()
                if len(part) >= 1:
                    items.append(part)
            continue

        if _CONSTRAINT_RE.search(clause):
            constraints.append(clause)
            continue

        if idx == 0 and not subject:
            subject = clause
            continue

        behaviors.append(clause)

    return {
        "subject": subject or (behaviors.pop(0) if behaviors else "未命名需求"),
        "constraints": constraints,
        "items": items,
        "item_label": item_label,
        "behaviors": behaviors,
    }


def _unique(seq: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for s in seq:
        key = s.replace(" ", "")
        if key and key not in seen:
            seen.add(key)
            out.append(s)
    return out


def build_mock_spec(input_text: str, mode: str = "extract") -> str:
    """把一段自然语言输入渲染成一份可解析的 OpenSpec 草稿。"""
    text = (input_text or "").strip()
    if not text:
        text = "未命名需求"
    parsed = _analyze(text)
    if mode == "decompose":
        return _build_decompose(parsed, text)
    return _build_extract(parsed, text)


def _build_extract(p: dict, text: str) -> str:
    subject = p["subject"]
    items = _unique(p["items"])
    constraints = _unique(p["constraints"])
    behaviors = _unique(p["behaviors"])

    shall: list[str] = [f"实现「{subject}」并提供确定性结果"]
    shall += [f"满足约束「{c}」" for c in constraints]
    if items:
        label = p.get("item_label") or "检查项"
        shall.append(f"覆盖以下{label}：{'、'.join(items)}")

    lines = "\n".join(f"- The system SHALL {s}" for s in shall)

    abnormal = ""
    if behaviors:
        ab_lines = "\n".join(f"- The system SHALL {b}" for b in behaviors)
        abnormal = f"""
## RS-002: {subject} 的异常与处置

{ab_lines}
"""
    else:
        abnormal = f"""
## RS-002: {subject} 的异常处置

- The system SHALL 在输入非法或执行失败时拒绝继续并给出可诊断的错误信息
- The system SHALL 在异常路径下不破坏已有持久化状态
"""

    item_scn = ""
    if items:
        label = p.get("item_label") or "检查项"
        checks = "、".join(items[:6])
        item_scn = f"""
## Scenario: 逐项检查

- GIVEN 系统已完成初始化
- WHEN 依次执行{label}：{checks}
- THEN 系统 SHALL 为每一项给出通过或失败的明确结论
"""

    return f"""# {subject}

> Generated by yuleOSH spec generator (demo mock).

## RS-001: {subject}

{lines}

#### Reason

User input: {text[:300]}

## Scenario: {subject} 正常路径

- GIVEN 系统已初始化且前置条件满足
- WHEN 用户触发「{subject}」
- THEN 系统 SHALL 返回符合 RS-001 定义的结果
{abnormal}{item_scn}
"""


def _build_decompose(p: dict, text: str) -> str:
    subject = p["subject"]
    units = _unique(p["items"] + p["constraints"] + p["behaviors"]) or [subject]
    blocks = []
    for idx, unit in enumerate(units[:6], start=1):
        blocks.append(
            f"## SWR-{idx:03d}: {unit}\n\n"
            f"- The system SHALL 实现「{unit}」并可通过测试用例验证\n"
        )
    body = "\n".join(blocks)
    return f"""# {subject} — 需求拆解

> Generated by yuleOSH spec generator (demo mock, decompose mode).
> Source: {text[:200]}

{body}
## Scenario: 端到端验收

- GIVEN 全部 SWR 均已实现
- WHEN 执行一次完整业务流程
- THEN 系统 SHALL 逐条满足上述 SHALL 约束
"""


def make_mock_llm(mode: str = "extract", input_text: str = "") -> Callable[..., dict]:
    """返回一个符合 ``_call_llm`` 注入签名的 mock 客户端。

    ``input_text`` 是调用方的原始需求文本。``generate_spec`` 会给 user_prompt
    加指令前缀，直接解析 prompt 会污染标题，因此优先使用传入的原文。
    """

    def _llm(system_prompt: str, user_prompt: str, **kwargs) -> dict:
        source = input_text or _extract_source(user_prompt)
        content = build_mock_spec(source, mode=mode)
        return {
            "content": content,
            "model": "demo-mock",
            "usage": {"prompt_tokens": 120, "completion_tokens": 260, "total_tokens": 380},
            "finish_reason": "stop",
        }

    return _llm


def _extract_source(user_prompt: str, limit: int = 2000) -> str:
    """从 ``_build_user_prompt`` 拼接的文本中截取原始需求段落。"""
    text = user_prompt or ""
    lines = []
    for line in text.split("\n"):
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith(("#", ">", "基于以下描述", "请", "输出", "Instructions")):
            continue
        lines.append(stripped)
    joined = " ".join(lines).strip()
    return (joined or text.strip())[:limit]
